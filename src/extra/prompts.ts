//
// 模型可见的固定指令仍然集中在**提示词目录**里，只是扩展那一块**单独一个文件**：
//   • `src/core/prompt-catalog.ts` 的 `TOOL_PROMPT_TEXT` —— 每一项对应 `agent/tools/index.ts` 里
//     **内置拼装**的一个工具，那张名单（名字与顺序）是硬约束、有断言逐字钉着；
