// `extra`（层级 4）的文件。之所以敢这么开，**全靠本文件是个叶子模块**：
//
//   ★ 本文件**不许 import 任何东西**（连 `import type` 都不要）。
//
// 一旦这里出现 import，环就可能成立（core → extra → core），而 `tsc` 不一定报错、运行期也只在
// 特定加载顺序下才炸。闸门里有专门的断言扫这一点（`LAYER_ALLOW` 的目标必须是叶子模块），
// 不需要靠人记 —— 但也别去试探它。
//
