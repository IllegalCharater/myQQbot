// 看不出来，加扩展的人也会在一张写着 "canonical schema traversal order" 的表里找自己该插哪儿。
//
// ⚠️ **本文件是分层闸门里唯一的具名例外**：`scripts/check-layers.mjs` 的 `LAYER_ALLOW` 里写着
